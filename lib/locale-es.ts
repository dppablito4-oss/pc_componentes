export function levelNameEs(level: LevelId) {
  return levelNames[level] ?? spanishComponentName(levels[level].name);
}

export function levelTitleEs(level: LevelId) {
  return levelTitles[level] ?? levelNameEs(level);
}

export function partNameEs(
  part: Pick<Concept, 'name' | 'shortName'>,
  compact = false,
) {
  const short = spanishComponentName(part.shortName);
  return compact && short !== part.shortName
    ? short
    : spanishComponentName(part.name);
}

export function bilingualPartName(part: Pick<Concept, 'name' | 'shortName'>) {
  return `${partNameEs(part)} · ${part.name}`;
}

